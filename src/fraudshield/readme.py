"""The README's headline metrics table, generated from ``reports/`` (``make readme``).

Every number in the table is read from a report that a ``make`` target writes; a row whose report
does not exist yet says so instead of showing a number (CLAUDE.md rule 7). ``--check`` exits 1 if
the README is out of date (a unit test runs it too).
"""

from __future__ import annotations

import argparse
import json
import sys
from collections.abc import Callable
from dataclasses import dataclass
from pathlib import Path
from typing import Any

START = "<!-- metrics:start: generated by `make readme` from reports/; do not edit by hand -->"
END = "<!-- metrics:end -->"
PENDING_REAL = "pending: real-data training run ([PLAN.md](PLAN.md#deferred-real-data-runs))"


@dataclass(frozen=True)
class Row:
    area: str
    metric: str
    value: str
    source: str  # repo-relative report path, or "" when pending


def _load(path: Path) -> dict[str, Any] | None:
    return json.loads(path.read_text()) if path.is_file() else None


def _ms(v: float | None) -> str:
    return "-" if v is None else f"{v:.1f} ms"


def model_rows(reports: Path, datasets: tuple[str, ...]) -> list[Row]:
    for ds in datasets:
        rel = f"reports/{ds}/metrics.json"
        m = _load(reports / ds / "metrics.json")
        if m is None:
            continue
        full, base = m["evals"]["lgbm_full"], m["evals"].get("rules_only")

        def vs(key: str, fmt: Callable[[float], str], full: Any = full, base: Any = base) -> str:
            v = full["metrics"].get(key)
            b = base["metrics"].get(key) if base else None
            if v is None:
                return "-"
            return fmt(v) + ("" if b is None else f" (rules-only {fmt(b)})")

        savings = full["dollars"]["net_savings_vs_approve_all"]
        name = "IEEE-CIS" if ds == "ieee_cis" else ds.capitalize()
        return [
            Row("Model", f"PR-AUC, test window ({name})", vs("pr_auc", lambda x: f"{x:.3f}"), rel),
            Row(
                "Model",
                "Recall at 1 % false-positive rate",
                vs("recall_at_fpr_1pct", lambda x: f"{x:.1%}"),
                rel,
            ),
            Row("Model", "Net savings vs approve-all, test window", f"${savings:,.0f}", rel),
        ]
    return [
        Row("Model", "PR-AUC, recall at 1 % FPR, net savings (test window)", PENDING_REAL, ""),
    ]


def serving_rows(reports: Path) -> list[Row]:
    out = []
    b = _load(reports / "benchmarks" / "serving_inprocess.json")
    if b is not None:
        m, lat = b["model"], b["latency_ms"]
        out.append(Row("Serving", f"Single-request scoring p95, in-process ({m['trees_full']} trees)",
                       f"{_ms(lat['service']['p95'])} (degraded path {_ms(lat['service_degraded']['p95'])})",
                       "reports/benchmarks/serving_inprocess.md"))  # fmt: skip
    # the real champion first (when its report exists), then the synthetic production-sized model
    for sub, model in (
        ("loadtest-ieee_cis", "IEEE-CIS champion"),
        ("loadtest", "synthetic 500x63 model"),
    ):
        lt = _load(reports / sub / "results.json")
        if lt is not None:
            out += _loadtest_rows(lt, f"reports/{sub}/report.md", model)
    return out


def _loadtest_rows(lt: dict[str, Any], src: str, model: str) -> list[Row]:
    out = []
    sc = {s["name"]: s for s in lt["scenarios"]}
    target = lt["config"]["users"] * lt["config"]["rps_per_user"]
    if "normal" in sc:
        n = sc["normal"]
        cl, sv = n["client"], n["service"]
        out.append(Row("Serving", f"Load test, {model}, {target:.0f} req/s target (3 reason codes)",
                       f"{cl['rps']:.1f} req/s, {cl['failures']:,.0f} failed, p95 {_ms(cl['p95_ms'])} "
                       f"client / {_ms(sv['p95_ms'])} service", src))  # fmt: skip
        share = n.get("server", {}).get("fallback_share")
        if share is not None:
            out.append(Row("Serving", f"Requests on a fallback path under that load ({model})",
                           f"{share:.1%}", src))  # fmt: skip
    if "redis_killed" in sc:
        k = sc["redis_killed"]
        rec = k.get("recovery_s")
        out.append(Row("Resilience", f"Redis killed mid-load ({model})",
                       f"{(k['client'] or {}).get('failures', 0):,.0f} failed requests; "
                       + ("degraded scoring, recovered in "
                          f"{rec:.0f} s after restart" if rec is not None else "not recovered"),
                       src))  # fmt: skip
    return out


def ops_rows(reports: Path) -> list[Row]:
    out = []
    d = _load(reports / "drift" / "latest.json")
    if d is not None:
        drop = (d.get("pr_auc") or {}).get("relative_drop")
        bits = [
            f"{d['drift_share']:.0%} of top-20 features drifted",
            f"score PSI {d['score_psi']:.2f}",
        ]
        if drop is not None:
            bits.append(f"matured PR-AUC {-drop:+.0%}")
        out.append(Row("Monitoring", "Drift demo (injected fraud ring): detection",
                       ", ".join(bits) + (" → retrain triggered" if d.get("should_retrain") else ""),
                       "reports/drift/demo-summary.md"))  # fmt: skip
    real = _load(reports / "drift-ieee_cis" / "daily.json")
    if real is not None:
        fired = [d for d in real["days"] if d["triggers"]]
        kinds: dict[str, int] = {}
        for d in fired:
            for t in d["triggers"]:
                kinds[t.split(":")[0]] = kinds.get(t.split(":")[0], 0) + 1
        detail = ", ".join(f"{k} {v}" for k, v in sorted(kinds.items()))
        out.append(Row("Monitoring", "Daily drift job on the real IEEE-CIS test window (no injection)",
                       f"{len(fired)} of {len(real['days'])} days would retrain ({detail})",
                       "reports/drift-ieee_cis/daily.md"))  # fmt: skip
    demo = _load(reports / "demo" / "demo-check.json")
    if demo is not None:
        out.append(Row("Deployment", "Single-container demo, peak memory",
                       f"{demo['peak_mem_mib']:.0f} MiB at {demo['rate_per_s']:.0f} tx/s "
                       f"for {demo['minutes']:.0f} min (limit 1,024 MiB)",
                       "reports/demo/demo-check.md"))  # fmt: skip
    qs = _load(reports / "demo" / "quickstart.json")
    if qs is not None and all(qs["checks"].values()):
        build = "cold build" if qs.get("cold_build") else "cached build"
        out.append(Row("Deployment", "README quickstart: fresh clone to a working demo",
                       f"{qs['total_s'] / 60:.1f} min ({build}; base images cached)",
                       "reports/demo/quickstart.md"))  # fmt: skip
    return out


def build_rows(reports: Path, datasets: tuple[str, ...] = ("ieee_cis", "sparkov")) -> list[Row]:
    return model_rows(reports, datasets) + serving_rows(reports) + ops_rows(reports)


def render(rows: list[Row]) -> str:
    lines = [START, "", "| Area | Metric | Value | Source |", "|---|---|---|---|"]
    for r in rows:
        src = f"[{Path(r.source).name}]({r.source})" if r.source else "-"
        lines.append(f"| {r.area} | {r.metric} | {r.value} | {src} |")
    lines += ["", END]
    return "\n".join(lines)


def updated(readme_text: str, block: str) -> str:
    a, b = readme_text.find(START), readme_text.find(END)
    if a == -1 or b == -1 or b < a:
        raise ValueError("README has no metrics markers")
    return readme_text[:a] + block + readme_text[b + len(END) :]


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(prog="python -m fraudshield.readme")
    p.add_argument("--readme", type=Path, default=Path("README.md"))
    p.add_argument("--reports", type=Path, default=Path("reports"))
    p.add_argument("--check", action="store_true", help="exit 1 if the README is stale")
    args = p.parse_args(argv)
    text = args.readme.read_text()
    new = updated(text, render(build_rows(args.reports)))
    if args.check:
        if new != text:
            print("README metrics are stale: run `make readme`", file=sys.stderr)
            return 1
        return 0
    args.readme.write_text(new)
    print(f"updated {args.readme}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
