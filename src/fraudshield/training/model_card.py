"""Render ``docs/model_card.md`` from a training report (``reports/<ds>/metrics.json``).

Every number in the card comes from the report written by ``train.py``; nothing is typed in.
"""

from __future__ import annotations

import json
from pathlib import Path
from typing import Any

from fraudshield.training.evaluate import to_markdown

_LIMITATIONS = """\
- Labels and their availability times are simulated from historical data (ADR-0005); real chargeback delays are longer and variable.
- IEEE-CIS timestamps are synthetic (2017-12-01 + TransactionDT, ADR-0004); hour/weekday features are relative to that clock.
- The cost matrix is an assumption (`configs/costs.yaml`); see the sensitivity sweep before relying on dollar figures.
- Entity ids are reconstructed (`card1_addr1_D1n` / `cc_num`) and can merge or split real customers.
- Performance is measured on one time-ordered test window; it will drift. Monitoring and retraining are covered in Phases 5-6."""


def _fmt(v: Any) -> str:
    if isinstance(v, float):
        return f"{v:.4f}" if abs(v) < 10 else f"{v:,.0f}"
    return str(v)


def render_model_card(report: dict[str, Any]) -> str:
    import polars as pl

    meta, data = report["meta"], report["data"]
    comparison = to_markdown(pl.DataFrame(report["comparison"]))
    seg_rows = [
        {"segment": s, **{k: m.get(k) for k in ("n", "n_pos", "pr_auc", "roc_auc", "total_cost")}}
        for s, m in report["segments"].items()
    ]
    segments = to_markdown(pl.DataFrame(seg_rows)) if seg_rows else "_no segments_\n"
    splits = "\n".join(
        f"| {name} | {r['start']}-{r['end']} | {_fmt(data['rows'].get(name, 0))} | {_fmt(data['positives'].get(name, 0))} |"
        for name, r in data["splits"].items()
    )
    costs = "\n".join(f"| `{k}` | {_fmt(v)} |" for k, v in report["costs"].items())
    params = "\n".join(f"| `{k}` | {_fmt(v)} |" for k, v in sorted(report["params"].items()))
    return f"""# Model card: {meta["registered_model"]} v{meta["model_version"]} ({meta["dataset"]})

_Generated by `fraudshield model-card` from `{report["report_path"]}`. Do not edit by hand._

## Model details

- **Type:** LightGBM binary classifier (full features) + request-only "degraded" fallback, isotonic/Platt calibration, cost-sensitive decision policy.
- **Registry:** `models:/{meta["registered_model"]}@challenger` (version {meta["model_version"]}, MLflow run `{meta["run_id"]}`).
- **Code:** git `{meta["git_sha"]}`; feature set `{meta["feature_set_hash"][:12]}`; raw data manifest `{meta["raw_manifest_hash"][:12]}`.
- **Trained:** {meta["created_at"]}. Calibration: {report["calibration"]["full"]} (full), {report["calibration"]["degraded"]} (degraded).

## Intended use

Real-time scoring of card-not-present transactions into approve / review / block, with three human-readable reason codes per decision for analysts. Not for automated adverse decisions without the review queue and rule overrides.

## Data and splits

Time-based splits with {data["gap_days"]}-day label-delay gaps (days are counted from the dataset origin).

| split | days | rows | frauds |
|---|---|---|---|
{splits}

## Features

{report["features"]["n_full"]} features ({report["features"]["n_request_only"]} request-only for the degraded model), all point-in-time correct. See `src/fraudshield/features/definitions.py`.

## Test-window results

{comparison}
Card precision@100 is averaged over test days. Net savings are relative to approving everything and to the rules-only baseline under the cost assumptions below.

### New vs known entities (full model)

{segments}
## Cost assumptions

| parameter | value |
|---|---|
{costs}

## Hyperparameters (full model)

| parameter | value |
|---|---|
{params}

## Limitations

{_LIMITATIONS}
"""


def write_model_card(report_path: Path, out: Path) -> Path:
    report = json.loads(report_path.read_text())
    report["report_path"] = str(report_path)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text(render_model_card(report))
    return out
